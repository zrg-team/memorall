#!/usr/bin/env node
/**
 * Bundles HyperFrames' design presets (frame-presets/<slug>/FRAME.md from
 * heygen-com/hyperframes, the "premade frames" of hyperframes.dev/design) into
 * src/services/flows-integrations/tools/hyperframes/frame-presets.generated.ts,
 * verbatim, from one pinned commit.
 *
 *   node tools/sync-hyperframes-frame-presets.mjs [commit]
 *
 * Bump COMMIT (or pass one) to update, then review the diff and run the
 * hyperframes tool tests.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "heygen-com/hyperframes";
const COMMIT = process.argv[2] || "fff3636fe727512af54c876982c73050ca2c8fa5";
const PRESETS = [
	"biennale-yellow",
	"blockframe",
	"blue-professional",
	"bold-poster",
	"broadside",
	"capsule",
	"cartesian",
	"cobalt-grid",
	"code-editorial",
	"coral",
	"creative-mode",
	"daisy-days",
	"editorial-forest",
];
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(
	root,
	"src/services/flows-integrations/tools/hyperframes/frame-presets.generated.ts",
);

const fetchText = async (file) => {
	const url = `https://raw.githubusercontent.com/${REPO}/${COMMIT}/${file}`;
	const response = await fetch(url);
	if (!response.ok) throw new Error(`${response.status} ${url}`);
	return (await response.text()).replace(/\r\n?/g, "\n");
};

const frames = {};
for (const slug of PRESETS) {
	frames[slug] = await fetchText(
		`skills/hyperframes-creative/frame-presets/${slug}/FRAME.md`,
	);
	if (!frames[slug].startsWith("---\n")) {
		throw new Error(`${slug}/FRAME.md has no frontmatter`);
	}
}

const body = [
	"// Generated by tools/sync-hyperframes-frame-presets.mjs. Do not edit.",
	`// Source: https://github.com/${REPO}/tree/${COMMIT}/skills/hyperframes-creative/frame-presets`,
	"// Copyright 2026 HeyGen, Inc. Licensed under the Apache License, Version 2.0",
	"// (public/vendors/hyperframes/LICENSE-hyperframes.txt). Unmodified FRAME.md files.",
	"",
	`export const HYPERFRAMES_FRAME_PRESETS_COMMIT = ${JSON.stringify(COMMIT)};`,
	"",
	"export const HYPERFRAMES_FRAME_PRESET_FILES: Record<string, string> = {",
	...PRESETS.map((slug) => `\t${JSON.stringify(slug)}: ${JSON.stringify(frames[slug])},`),
	"};",
	"",
].join("\n");
writeFileSync(out, body);
console.log(`Wrote ${PRESETS.length} frame presets from ${REPO}@${COMMIT.slice(0, 7)} to ${path.relative(root, out)}`);
