#!/usr/bin/env node
// Writes which model architectures each transformers.js pipeline task can load,
// read from the installed library itself (its SUPPORTED_TASKS and the Auto
// model classes behind them). The media studios use it to tell a Hub repo the
// browser runtime can run from one it cannot, before anything is downloaded.
//
// Run after upgrading @huggingface/transformers:
//   node tools/generate-pipeline-architectures.mjs
// (a unit test fails while the checked-in table is stale).
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(
	root,
	"src/services/llm/registry/pipeline-architectures.generated.ts",
);

export async function readPipelineArchitectures(projectRoot = root) {
	const pipelines = await import(
		pathToFileURL(
			path.join(
				projectRoot,
				"node_modules/@huggingface/transformers/src/pipelines/index.js",
			),
		).href
	);
	const table = {};
	for (const [task, spec] of Object.entries(pipelines.SUPPORTED_TASKS)) {
		const models = Array.isArray(spec.model) ? spec.model : [spec.model];
		const accepted = new Set();
		let open = false;
		for (const model of models) {
			// A base class that falls back to constructing anything accepts all.
			if (!model?.MODEL_CLASS_MAPPINGS || model.BASE_IF_FAIL) open = true;
			for (const mapping of model?.MODEL_CLASS_MAPPINGS ?? []) {
				for (const [modelType, className] of mapping.entries()) {
					accepted.add(modelType);
					// A config may name the class instead of the type; the library
					// resolves that too.
					accepted.add(Array.isArray(className) ? className[0] : className);
				}
			}
		}
		// An open task accepts anything: listing what it names adds nothing.
		table[task] = { open, architectures: open ? [] : [...accepted].sort() };
	}
	return { aliases: { ...pipelines.TASK_ALIASES }, tasks: table };
}

export function renderPipelineArchitectures({ aliases, tasks }) {
	return `// Generated by tools/generate-pipeline-architectures.mjs from the installed
// @huggingface/transformers. Do not edit by hand.

export interface PipelineArchitectures {
	/** The task accepts any architecture (its model class falls back to a base). */
	open: boolean;
	/** \`config.model_type\` values (and class names) the task can load. */
	architectures: readonly string[];
}

export const PIPELINE_TASK_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(aliases, null, "\t")};

export const PIPELINE_ARCHITECTURES: Readonly<
	Record<string, PipelineArchitectures>
> = ${JSON.stringify(tasks, null, "\t")};
`;
}

if (
	process.argv[1] &&
	fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
) {
	const data = await readPipelineArchitectures();
	writeFileSync(OUTPUT, renderPipelineArchitectures(data));
	console.log(`Wrote ${path.relative(root, OUTPUT)}`);
}
